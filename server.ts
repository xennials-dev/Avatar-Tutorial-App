app.post('/api/projects/:id/restore', (req, res) => {
  const { id } = req.params;
  const { targetVersion } = req.body;
  const projectIdx = projects.findIndex((p) => p.id === id);

  if (projectIdx === -1) {
    return res.status(404).json({ error: 'Project not found' });
  }

  const project = projects[projectIdx];
  const target = (project.history || []).find((h: any) => h.version === Number(targetVersion));

  if (!target) {
    return res.status(404).json({ error: `Version v${targetVersion} not found in project history` });
  }

  const now = new Date().toISOString();
  // Snapshot current active state before restoring
  const currentSnapshot = {
    version: project.version || 1,
    timestamp: project.createdAt || now,
    title: project.title,
    description: project.description,
    duration: project.duration,
    avatar: project.avatar,
    voice: project.voice,
    provider: project.provider,
    model: project.model,
    steps: project.steps,
    prompt: project.prompt,
    note: `Archived automatically prior to restoring v${targetVersion}.`,
  };

  const updatedProj = {
    ...project,
    title: target.title,
    description: target.description,
    duration: target.duration,
    avatar: target.avatar,
    voice: target.voice,
    provider: target.provider,
    model: target.model,
    steps: target.steps,
    prompt: target.prompt,
    version: target.version,
    createdAt: now,
    history: [currentSnapshot, ...(project.history || []).filter((h: any) => h.version !== target.version)],
  };

  projects[projectIdx] = updatedProj;
  res.json({ success: true, project: updatedProj, restoredVersion: target.version });
});

