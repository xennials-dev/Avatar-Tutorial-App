app.get('/api/providers/:id/models', (req, res) => {
  const providerId = req.params.id as ProviderId;
  const configs: Record<string, any> = getProviderConfigs();
  const cfg = configs[providerId];
  if (!cfg) {
    return res.status(404).json({ error: 'Provider not found' });
  }
  res.json({ provider: providerId, models: cfg.models });
});

